--       GROUP 상품은 ProductRepositoryImpl 의 3가지 조회 메서드
--       (findTopLikedProducts / findTopDiscountedProducts /
--       findTopRepurchaseProducts)가 각각 30건 이상 반환되도록 구성한다.
--       GROUP 상품은 모두 STANDARD 리프 카테고리 정확히 1개와 매핑되고
