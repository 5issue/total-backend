--    GROUP 상품에는 재고 row 를 만들지 않는다.
--    수량은 시연용이라 p.id 기반 산술로 적당히 분포시킨다.
--      base_quantity     : 50 ~ 499 (재고 보유량)
--      reserved_quantity : 0 ~ 11   (예약/홀드 수량, 대부분 소량)
--    available = base - reserved 는 항상 양수다.
-- ============================================================
INSERT INTO product_inventory (product_id, base_quantity, reserved_quantity, updated_at)
SELECT p.id,
       50 + (p.id * 17) % 450,
       (p.id * 7) % 12,
       NOW()
FROM product p
WHERE p.type = 'UNIT';

