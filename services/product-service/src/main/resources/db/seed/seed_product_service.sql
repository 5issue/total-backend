--   3. category  - DISPLAY (최상위 + 하위)
--   4a. product  - GROUP 상품 100개 (SKU-0001 ~ SKU-0100, short_description 포함)
--   4b. product  - UNIT 상품 (GROUP 당 1~3개, parent_id 로 GROUP 에 연결, short_description=NULL)
--   5. product_category - STANDARD 리프 매핑 (GROUP 기준, is_main = true, 100건)
--   6. product_category - DISPLAY 매핑 (GROUP 기준, is_main = false)
--   7. product_spec     - UNIT 상품 전부 (product_spec 은 UNIT 에만 매핑)
--   8. product_inventory - UNIT 상품 전부 (재고도 UNIT 단위로만 관리)
--
-- 실행 방법 (Flyway 등 마이그레이션 도구로 자동 실행되지 않음, 수동 실행 전용):
--   - psql:
--       docker exec -i kurly-postgres-product psql -U postgres -d product \
--         < src/main/resources/db/seed/seed_product_service.sql
--   - DBeaver:
--       이 파일을 열고 "SQL 스크립트 실행"(Alt+X, 또는 툴바의 ▷▷ 아이콘)으로
--       전체를 실행한다. 단일 문장 실행(Ctrl+Enter)이 아니라 스크립트 실행이어야
--       BEGIN ~ COMMIT 과 여러 INSERT 문이 순서대로 처리된다.
--       접속 DB 클라이언트 인코딩이 UTF-8 인지 확인할 것(한글 데이터 포함).
--
-- 주의:
--   - 멱등(idempotent)하지 않다. category/product 에 이름/sku 유니크 제약이
--     없으므로, 이미 데이터가 있는 상태에서 재실행하면 중복 INSERT 된다.
--     재실행 전 아래 TRUNCATE 블록의 주석을 풀거나 직접 테이블을 비울 것.
--   - product.type CHECK 제약을 GROUP/UNIT 기준으로 재정의한다. 과거 스키마
--     (MAIN/OPTION)가 남아있던 로컬 DB를 엔티티(Product.ProductType)와
